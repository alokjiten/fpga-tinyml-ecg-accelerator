module tinyml_top(
    input clk,
    input signed [15:0] rr,
    input signed [15:0] energy,
    output [2:0] class
);

// ----------------------------------------------------
// Layer 1 outputs (16 neurons)
// ----------------------------------------------------

wire signed [15:0] l1_0,l1_1,l1_2,l1_3,l1_4,l1_5,l1_6,l1_7;
wire signed [15:0] l1_8,l1_9,l1_10,l1_11,l1_12,l1_13,l1_14,l1_15;


// ----------------------------------------------------
// Layer 2 outputs (8 neurons)
// ----------------------------------------------------

wire signed [15:0] l2_0,l2_1,l2_2,l2_3,l2_4,l2_5,l2_6,l2_7;


// ----------------------------------------------------
// Dense Layer 1 (Input → 16 neurons)
// ----------------------------------------------------

dense_layer1 L1(

.clk(clk),

.rr(rr),
.energy(energy),

.out0(l1_0),
.out1(l1_1),
.out2(l1_2),
.out3(l1_3),
.out4(l1_4),
.out5(l1_5),
.out6(l1_6),
.out7(l1_7),

.out8(l1_8),
.out9(l1_9),
.out10(l1_10),
.out11(l1_11),
.out12(l1_12),
.out13(l1_13),
.out14(l1_14),
.out15(l1_15)

);


// ----------------------------------------------------
// Dense Layer 2 (16 → 8 neurons)
// ----------------------------------------------------

dense_layer2 L2(

.clk(clk),

.in0(l1_0),
.in1(l1_1),
.in2(l1_2),
.in3(l1_3),
.in4(l1_4),
.in5(l1_5),
.in6(l1_6),
.in7(l1_7),

.in8(l1_8),
.in9(l1_9),
.in10(l1_10),
.in11(l1_11),
.in12(l1_12),
.in13(l1_13),
.in14(l1_14),
.in15(l1_15),

.out0(l2_0),
.out1(l2_1),
.out2(l2_2),
.out3(l2_3),
.out4(l2_4),
.out5(l2_5),
.out6(l2_6),
.out7(l2_7)

);


// ----------------------------------------------------
// Output Layer (8 → Class)
// ----------------------------------------------------

output_layer L3(

.clk(clk),

.n0(l2_0),
.n1(l2_1),
.n2(l2_2),
.n3(l2_3),
.n4(l2_4),
.n5(l2_5),
.n6(l2_6),
.n7(l2_7),

.class(class)

);

endmodule